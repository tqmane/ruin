#!/usr/bin/env python3
"""Embed the unchanged resource bundle for recovery after dylib-only injection."""
import argparse
import hashlib
from pathlib import Path


def bundle_files(bundle):
    bundle = Path(bundle)
    if bundle.is_symlink() or not bundle.is_dir():
        raise ValueError("Expected a resource bundle directory, not a symlink")
    files = []
    for path in sorted(bundle.rglob("*")):
        if path.is_symlink():
            raise ValueError(f"Resource bundle must not contain symlinks: {path}")
        if path.is_file():
            files.append((path.relative_to(bundle).as_posix(), path.read_bytes()))
        elif not path.is_dir():
            raise ValueError(f"Unsupported resource file: {path}")
    if not any(name == "Info.plist" for name, _ in files):
        raise ValueError("Resource bundle must contain Info.plist")
    return files


def bundle_digest(files):
    digest = hashlib.sha256()
    for name, data in files:
        name_bytes = name.encode("utf-8")
        # Length-prefix each field so paths and arbitrary binary contents cannot
        # change record boundaries while retaining the same digest input.
        for value in (name_bytes, data):
            digest.update(len(value).to_bytes(8, "big"))
            digest.update(value)
    return digest.hexdigest()


def c_string(value):
    return '"' + "".join(
        chr(byte) if 32 <= byte < 127 and byte not in (34, 92) else f"\\{byte:03o}"
        for byte in value.encode("utf-8")
    ) + '"'


def render_header(files):
    lines = [
        "// Generated by tools/embed_resources.py. Do not edit.",
        "#ifndef RUIN_EMBEDDED_RESOURCES_H",
        "#define RUIN_EMBEDDED_RESOURCES_H",
        "#include <stddef.h>",
        "",
        "typedef struct {",
        "    const char *path;",
        "    const unsigned char *bytes;",
        "    size_t length;",
        "} RUINEmbeddedResourceFile;",
        "",
        f'static const char RUINEmbeddedResourceDigest[] = "{bundle_digest(files)}";',
        "",
    ]
    for index, (_, data) in enumerate(files):
        lines.append(f"static const unsigned char RUINEmbeddedResourceData{index}[] = {{")
        # Empty files still need a valid C array; their entry length remains 0.
        backing = data or b"\0"
        for offset in range(0, len(backing), 16):
            lines.append("    " + ", ".join(f"0x{byte:02x}" for byte in backing[offset:offset + 16]) + ",")
        lines.extend(["};", ""])
    lines.append("static const RUINEmbeddedResourceFile RUINEmbeddedResourceFiles[] = {")
    for index, (name, data) in enumerate(files):
        lines.append(f"    {{{c_string(name)}, RUINEmbeddedResourceData{index}, {len(data)}}},")
    lines.extend(["};", "#endif", ""])
    return "\n".join(lines)


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("bundle", type=Path)
    parser.add_argument("header", type=Path)
    args = parser.parse_args()
    contents = render_header(bundle_files(args.bundle))
    args.header.parent.mkdir(parents=True, exist_ok=True)
    args.header.write_text(contents, encoding="ascii", newline="\n")


if __name__ == "__main__":
    main()
