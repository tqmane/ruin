#!/usr/bin/env python3
"""Exercise the real loader insertion and Apple signing tools on our own Mach-O."""
from pathlib import Path
import shutil
import struct
import subprocess
import sys
import tempfile

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / 'tools'))
from macho_integrity import verify_packaged
from distribute import dylib_rpaths, verify_dylib
from prepare_livecontainer import prepare_livecontainer
from verify_embedded_resources import verify_embedded_resources

LC_RPATH = 0x8000001C
LIVE_CONTAINER_RPATHS = ('@executable_path/../../Tweaks', '@loader_path')


def run(*args):
    result = subprocess.run([str(arg) for arg in args], capture_output=True, text=True)
    if result.returncode:
        raise RuntimeError(f'{args[0]} failed: {result.stderr}\n{result.stdout}')
    return result.stdout.strip()


def commands(data):
    """Read only the thin 64-bit Mach-O fixtures generated by this test."""
    header = struct.unpack_from('<8I', data)
    assert header[0] == 0xFEEDFACF and header[3] == 6
    offset = 32
    result = []
    for _ in range(header[4]):
        command, size = struct.unpack_from('<II', data, offset)
        assert size >= 8 and size % 4 == 0 and offset + size <= 32 + header[5]
        result.append((command, data[offset:offset + size]))
        offset += size
    assert offset == 32 + header[5]
    return header, result


def append_livecontainer_rpaths(path, imports=1):
    """Reproduce upstream LCPatchAddRPath, including its 44/28-byte commands."""
    data = bytearray(path.read_bytes())
    header, original_commands = commands(data)
    added = bytearray()
    for value in LIVE_CONTAINER_RPATHS:
        name = value.encode('ascii') + b'\0'
        size = 12 + ((len(name) + 7) & ~7)
        added += struct.pack('<III', LC_RPATH, size, 12) + name.ljust(size - 12, b'\0')
    assert len(added) == 44 + 28
    added *= imports
    end = 32 + header[5]
    section_offsets = []
    for kind, raw in original_commands:
        if kind == 0x19:  # LC_SEGMENT_64
            count = struct.unpack_from('<I', raw, 64)[0]
            for index in range(count):
                offset = struct.unpack_from('<I', raw, 72 + 80 * index + 48)[0]
                if offset:
                    section_offsets.append(offset)
    assert section_offsets and end + len(added) <= min(section_offsets)
    assert not any(data[end:end + len(added)]), 'LC fixture would overwrite non-padding bytes'
    data[end:end + len(added)] = added
    struct.pack_into('<II', data, 16, header[4] + 2 * imports, header[5] + len(added))
    path.write_bytes(data)


def immutable_dylib_contents(path):
    """Compare every non-signature payload byte and unaffected load command."""
    data = path.read_bytes()
    header, load_commands = commands(data)
    signature_start = len(data)
    fixed = []
    for kind, raw in load_commands:
        if kind == 0x1D:  # LC_CODE_SIGNATURE
            signature_start = struct.unpack_from('<I', raw, 8)[0]
        elif kind != LC_RPATH:
            if kind == 0x19 and raw[8:24].rstrip(b'\0') == b'__LINKEDIT':
                # codesign may resize the segment that owns the final signature.
                raw = raw[:32] + b'\0' * 8 + raw[40:48] + b'\0' * 8 + raw[56:]
            fixed.append(raw)
    return header[:4] + header[6:], fixed, data[32 + header[5]:signature_start]


def check_livecontainer_preparation(directory, library):
    clean = directory / 'clean-LiveContainer.dylib'
    prepare_livecontainer(library, clean)
    assert clean.read_bytes() == library.read_bytes(), 'Clean preparation changed the signed dylib'
    snapshots = {}
    expected_rpaths = {}
    contaminated_slices = []
    for architecture, imports in (('arm64', 2), ('arm64e', 1)):
        thin = directory / f'lc-{architecture}.dylib'
        run('lipo', library, '-thin', architecture, '-output', thin)
        snapshots[architecture] = immutable_dylib_contents(thin)
        expected_rpaths[architecture] = dylib_rpaths(library, architecture)
        append_livecontainer_rpaths(thin, imports)
        contaminated_slices.append(thin)
    contaminated = directory / 'contaminated.dylib'
    run('lipo', '-create', *contaminated_slices, '-output', contaminated)
    run('codesign', '--force', '--sign', '-', '--timestamp=none', contaminated)
    original_bytes = contaminated.read_bytes()
    try:
        verify_dylib(contaminated)
    except ValueError as error:
        assert 'rpath' in str(error).lower(), error
    else:
        raise AssertionError('Duplicate LC_RPATH passed distribution verification')

    prepared = directory / 'repaired-LiveContainer.dylib'
    prepare_livecontainer(contaminated, prepared)
    assert contaminated.read_bytes() == original_bytes, 'Preparation modified its input dylib'
    verify_dylib(prepared, for_livecontainer=True)
    reimported_slices = []
    for architecture in ('arm64', 'arm64e'):
        assert dylib_rpaths(prepared, architecture) == expected_rpaths[architecture]
        thin = directory / f'repaired-{architecture}.dylib'
        run('lipo', prepared, '-thin', architecture, '-output', thin)
        assert immutable_dylib_contents(thin) == snapshots[architecture], architecture
        append_livecontainer_rpaths(thin)
        reimported_slices.append(thin)
    reimported = directory / 'reimported.dylib'
    run('lipo', '-create', *reimported_slices, '-output', reimported)
    run('codesign', '--force', '--sign', '-', '--timestamp=none', reimported)
    verify_dylib(reimported)
    for architecture in ('arm64', 'arm64e'):
        assert dylib_rpaths(reimported, architecture) == (
            expected_rpaths[architecture] + list(LIVE_CONTAINER_RPATHS))
    print('PASS: asymmetric repeated LC imports are repaired without changing source or payload; one fresh import has unique RPATHs.')


def main():
    verify_dylib(ROOT / 'build/RUIN.dylib')
    print('PASS: built RUIN.dylib is a signed arm64+arm64e universal binary with authorized dependencies.')
    sdk = run('xcrun', '--sdk', 'iphoneos', '--show-sdk-path')
    with tempfile.TemporaryDirectory(prefix='ruin-packaging-') as temporary:
        directory = Path(temporary)
        actual_prepared = directory / 'RUIN-LiveContainer.dylib'
        prepare_livecontainer(ROOT / 'build/RUIN.dylib', actual_prepared)
        assert actual_prepared.read_bytes() == (ROOT / 'build/RUIN.dylib').read_bytes()
        verify_embedded_resources(actual_prepared, ROOT / 'resources/RUINResources.bundle')
        print('PASS: preparing the real clean build preserves its signature, payload and embedded resources byte-for-byte.')
        source = directory / 'fixture.c'
        original = directory / 'original'
        packaged = directory / 'packaged'
        source.write_text('#include <stdio.h>\nvolatile int value = 42;\n'
                          'int main(void) { return printf("RUIN fixture: %d\\n", value) < 0; }\n')
        run('xcrun', '--sdk', 'iphoneos', 'clang', '-arch', 'arm64', '-isysroot', sdk,
            '-miphoneos-version-min=18.0', '-Wl,-headerpad,0x1000', source, '-o', original)
        run('codesign', '--force', '--sign', '-', '--timestamp=none', original)
        original_bytes = original.read_bytes()
        shutil.copy2(original, packaged)
        run(ROOT / 'build/insert_dylib', '--inplace', '--all-yes', '--strip-codesig',
            '@executable_path/Frameworks/RUIN.dylib', packaged)
        verify_packaged(original_bytes, packaged.read_bytes())
        run('codesign', '--force', '--sign', '-', '--timestamp=none', packaged)
        run('codesign', '--verify', '--strict', packaged)
        count = verify_packaged(original_bytes, packaged.read_bytes())
        print(f'PASS: pinned insert_dylib and Apple ad-hoc signing preserve {count} original sections.')

        library = directory / 'fixture.dylib'
        slices = []
        for arch in ('arm64', 'arm64e'):
            thin = directory / f'fixture-{arch}.dylib'
            run('xcrun', '--sdk', 'iphoneos', 'clang', '-arch', arch, '-isysroot', sdk,
                '-miphoneos-version-min=18.0', '-dynamiclib', '-Wl,-no_adhoc_codesign',
                '-Wl,-install_name,@rpath/RUIN.dylib', '-Wl,-headerpad,0x1000',
                '-Wl,-rpath,/usr/lib/swift', '-Wl,-rpath,@executable_path/Frameworks',
                source, '-o', thin)
            slices.append(thin)
        run('lipo', '-create', *slices, '-output', library)
        try:
            verify_dylib(library)
        except subprocess.CalledProcessError:
            pass
        else:
            raise AssertionError('Unsigned dylib passed distribution verification')
        run('codesign', '--force', '--sign', '-', '--timestamp=none', library)
        verify_dylib(library)
        print('PASS: synthetic arm64+arm64e fixture rejects unsigned dylibs and accepts a valid ad-hoc signature.')
        check_livecontainer_preparation(directory, library)


if __name__ == '__main__':
    main()
